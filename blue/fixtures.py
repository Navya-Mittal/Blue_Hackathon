"""Reference outputs from the LEGACY R model, used as ground truth for the parity proof.

The committed fixtures were produced by running legacy_models/credit_pd.R with real R on the committed
splits. Nothing in here is generated by Python, so the parity check is never circular.
Regenerate with:  python run_demo.py --regenerate-fixtures   (needs Rscript on PATH or $RSCRIPT)
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path

import pandas as pd

from .config import resolve
from .data import file_sha256


def fixtures_dir(cfg: dict, model_id: str) -> Path:
    """Folder holding the R reference outputs for a model."""
    return resolve(cfg, "fixtures_dir") / model_id


def regenerate(cfg: dict, model_id: str, splits: dict[str, Path]) -> Path:
    """Run the legacy R script with Rscript to rebuild the reference outputs and hash manifest."""
    rscript = os.environ.get("RSCRIPT") or shutil.which("Rscript")
    if not rscript:
        raise RuntimeError(
            "Rscript not found. Install R, or set $RSCRIPT, or keep using the committed fixtures."
        )
    script = resolve(cfg, "legacy_dir") / f"{model_id}.R"
    out = fixtures_dir(cfg, model_id)
    out.mkdir(parents=True, exist_ok=True)
    r = subprocess.run(
        [
            rscript,
            str(script),
            str(splits["train"]),
            str(out),
            str(splits["test"]),
            str(splits["edge"]),
        ],
        capture_output=True,
        text=True,
        timeout=300,
    )
    if r.returncode != 0:
        raise RuntimeError(f"R failed:\n{r.stderr[-2000:]}")
    ver = subprocess.run([rscript, "--version"], capture_output=True, text=True)
    manifest = {
        "model_id": model_id,
        "r_version": (ver.stdout or ver.stderr).strip(),
        "script_sha256": file_sha256(script),
        "inputs_sha256": {k: file_sha256(p) for k, p in splits.items()},
        "outputs": sorted(p.name for p in out.glob("*.csv")),
    }
    (out / "MANIFEST.json").write_text(json.dumps(manifest, indent=1), encoding="utf-8")
    return out


def load_reference(cfg: dict, model_id: str, splits: dict[str, Path]) -> dict:
    """Load R reference outputs and check they belong to the current splits and script."""
    d = fixtures_dir(cfg, model_id)
    man_path = d / "MANIFEST.json"
    if not man_path.exists():
        raise FileNotFoundError(
            f"No fixtures for {model_id} in {d}. Run with --regenerate-fixtures (needs R)."
        )
    man = json.loads(man_path.read_text(encoding="utf-8"))
    stale = [k for k, p in splits.items() if man["inputs_sha256"].get(k) != file_sha256(p)]
    if stale:
        raise RuntimeError(
            f"Fixtures were generated from different {stale} files than the current splits. "
            f"Re-run with --regenerate-fixtures."
        )
    script = resolve(cfg, "legacy_dir") / f"{model_id}.R"
    if man["script_sha256"] != file_sha256(script):
        raise RuntimeError(
            f"{script.name} changed since the fixtures were generated. Re-run with --regenerate-fixtures."
        )
    coefs = pd.read_csv(d / "coefficients.csv")
    return {
        "manifest": man,
        "coefficients": dict(zip(coefs["term"], coefs["estimate"])),
        "pred": {name: pd.read_csv(d / f"pred_{name}.csv") for name in ("test", "edge")},
    }
